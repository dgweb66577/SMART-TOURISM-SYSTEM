export function getRestaurantById(id: string): RestaurantDetail | undefined {
  const normalized = id.toLowerCase().replace(/['\s]/g, '-')
  return (
    RESTAURANTS_DATA.find((r) => r.id === id || r.slug === id) ||
    RESTAURANTS_DATA.find((r) => r.id.includes(normalized) || normalized.includes(r.id)) ||
    RESTAURANTS_DATA[0]
  )
}

